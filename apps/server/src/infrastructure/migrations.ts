// Any constant will do, as long as every NebulaDB process takes the same one.
const MIGRATION_LOCK = 7_265_001;

/**
 * Applies every migration the database has not seen yet, in order, in one
 * transaction: a boot either ends on the latest schema or leaves the database
 * as it found it. The advisory lock makes two processes started together
 * (a rolling restart) take turns instead of both creating the same table.
 */
export async function runMigrations(db: MigrationDb): Promise<void> {
  await db.transaction(async () => {
    await db.prepare("SELECT pg_advisory_xact_lock(?)").get(MIGRATION_LOCK);
    await db.exec(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        version INTEGER PRIMARY KEY,
        name TEXT NOT NULL,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )
    `);
    const applied = new Set(
      ((await db.prepare("SELECT version FROM schema_migrations").all()) as { version: number }[]).map(
        (row) => row.version,
      ),
    );
    const pending = MIGRATIONS.filter((m) => !applied.has(m.version)).sort((a, b) => a.version - b.version);
    for (const migration of pending) {
      await migration.up(db);
      await db
        .prepare("INSERT INTO schema_migrations (version, name) VALUES (?, ?)")
        .run(migration.version, migration.name);
      console.log(`[db] applied migration ${migration.version}: ${migration.name}`);
    }
  });
}
